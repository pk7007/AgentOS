"""docs/REASONS.md: every refusal reason AgentOS can give, where it is raised and the message that comes with it,
generated from the source so the list cannot fall behind the code.

A reason is a short code in a refusal (`PolicyDenied(..., reasons=[...])`, exit code 3) or in an admission
decision (`reasons.append(...)`). The scan reads the source's syntax tree; it does not run anything."""

import ast
import re
from collections import defaultdict
from pathlib import Path

from agentos.gen.reason_guide import MEANING, REMEDY

SRC = Path(__file__).resolve().parents[1]


def _strings(node) -> list[str]:
    if isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        return [e.value for e in node.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
    return []


def _text(node) -> str:
    """A message as written, with each computed part shown as an ellipsis."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return "".join(v.value if isinstance(v, ast.Constant) else "…" for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return _text(node.left) + _text(node.right)
    return "…"


def _message(call: ast.Call) -> str:
    if not call.args:
        return ""
    text = re.sub("…+", "…", _text(call.args[0]))
    return "" if text == "…" else text


def scan(src: Path = SRC) -> dict[str, dict]:
    """{reason: {"where": sorted "module.function" names, "message": the first message found}}."""
    found: dict[str, dict] = defaultdict(lambda: {"where": set(), "message": ""})
    for path in sorted(src.rglob("*.py")):
        module = path.relative_to(src).with_suffix("").as_posix().replace("/", ".")
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for fn in [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]:
            for node in ast.walk(fn):
                if not isinstance(node, ast.Call):
                    continue
                codes: list[str] = []
                for kw in node.keywords:
                    if kw.arg == "reasons":
                        codes += _strings(kw.value)
                f = node.func
                if (isinstance(f, ast.Attribute) and f.attr in ("append", "extend")
                        and isinstance(f.value, ast.Name) and f.value.id.endswith("reasons")):
                    for a in node.args:
                        if isinstance(a, ast.Constant) and isinstance(a.value, str):
                            codes.append(a.value)
                        codes += _strings(a)
                for code in codes:
                    entry = found[code]
                    entry["where"].add(f"{module}.{fn.name}")
                    if not entry["message"] and any(kw.arg == "reasons" for kw in node.keywords):
                        entry["message"] = _message(node)
    return {k: {"where": sorted(v["where"]), "message": v["message"]} for k, v in sorted(found.items())}


def render() -> str:
    reasons = scan()
    out = ["# Refusal reasons", "",
           "Generated by `agentos gen docs` from the source; do not edit by hand. A refusal exits with code 3 and",
           "names one or more of these codes (`--json` prints them under `reasons`). `docs/TROUBLESHOOTING.md`",
           "walks through the common situations.", "",
           f"{len(reasons)} reasons.", "",
           "| Reason | Raised in | Message | What to do |", "| --- | --- | --- | --- |"]
    for code, info in reasons.items():
        where = ", ".join(f"`{w}`" for w in info["where"][:4]) + (" …" if len(info["where"]) > 4 else "")
        msg = (info["message"] or MEANING.get(code, "")).replace("|", "/").replace("\n", " ")
        out.append(f"| `{code}` | {where} | {msg} | {REMEDY.get(code, '')} |")
    return "\n".join(out) + "\n"


def generate(path: Path) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return str(path)
