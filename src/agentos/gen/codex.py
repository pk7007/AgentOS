"""Generate a Codex plugin: manifest, skill, custom agent files, config snippet and a local marketplace."""

import json
from pathlib import Path

from agentos.gen import GenResult, Writer, load_agents, load_plugin_meta, skill_text
from agentos.gen.tomlw import dumps


def _agent_toml(t) -> str:
    data: dict = {"name": t.id, "description": t.description, "developer_instructions": t.instructions}
    if t.read_only:
        data["sandbox_mode"] = "read-only"
    if t.reasoning_hint:
        data["model_reasoning_effort"] = t.reasoning_hint
    if t.model_hint:
        data["model"] = t.model_hint
    return "# Generated by `agentos gen codex`. Edit definitions/agents instead.\n" + dumps(data)


def generate(defs_dir: Path, out_dir: Path, force: bool = False, max_threads: int = 4,
             max_depth: int = 2) -> GenResult:
    meta = load_plugin_meta(defs_dir)
    agents = load_agents(defs_dir)
    w = Writer(out_dir, force)
    manifest = {
        "name": meta["name"], "version": meta["version"], "description": meta["description"],
        "license": "MIT", "keywords": ["agents", "orchestration", "governance", "audit"],
        "skills": "./skills/",
        "interface": {"displayName": meta["display_name"], "shortDescription": meta["description"],
                      "category": "Coding", "capabilities": ["Interactive", "Read", "Write"]},
    }
    w.write(".codex-plugin/plugin.json", json.dumps(manifest, indent=2) + "\n")
    w.write("skills/agentos/SKILL.md", skill_text(defs_dir))
    snippet: dict = {"agents": {"max_threads": max_threads, "max_depth": max_depth}}
    for t in agents:
        w.write(f"agents/{t.id}.toml", _agent_toml(t))
        snippet["agents"][t.id] = {"description": t.description, "config_file": f"agents/{t.id}.toml"}
    w.write("config-snippet.toml",
            "# Copy what you want into your own config by hand. agentos never edits it for you.\n"
            + dumps(snippet))
    market = {
        "name": meta["name"], "interface": {"displayName": meta["display_name"]},
        "plugins": [{"name": meta["name"], "version": meta["version"],
                     "source": {"source": "local", "path": "./"},
                     "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                     "category": "Productivity"}],
    }
    w.write(".agents/plugins/marketplace.json", json.dumps(market, indent=2) + "\n")
    return w.finish()
