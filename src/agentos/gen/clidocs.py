"""docs/CLI.md: a reference of every command, sub-command and option, generated from the parser itself so it
cannot fall behind the code."""

import argparse
from pathlib import Path


def _sub_actions(parser: argparse.ArgumentParser):
    return [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]


REPO = Path(__file__).resolve().parents[3]


def _shown(value) -> str:
    """A default path inside the checkout is shown relative to it, so the reference is the same on every
    machine and names no one's home folder."""
    if isinstance(value, Path):
        try:
            return value.resolve().relative_to(REPO).as_posix()
        except ValueError:
            return value.name
    return str(value)


def _options(parser: argparse.ArgumentParser) -> list[str]:
    rows = []
    for a in parser._actions:
        if (isinstance(a, (argparse._HelpAction, argparse._SubParsersAction)) or a.help == argparse.SUPPRESS
                or a.dest in ("json", "actor")):
            continue
        name = ", ".join(a.option_strings) if a.option_strings else a.dest.upper()
        if a.choices and not a.option_strings:
            name += " {" + ",".join(map(str, a.choices)) + "}"
        default = "" if a.default in (None, False, argparse.SUPPRESS) or not a.option_strings else f" (default {_shown(a.default)})"
        rows.append(f"| `{name}` | {(a.help or '').replace('|', '/')}{default} |")
    return rows


def _walk(parser: argparse.ArgumentParser, path: list[str], helps: dict, out: list[str]) -> None:
    subs = _sub_actions(parser)
    if path:
        level = "#" * min(len(path) + 1, 4)
        out.append(f"{level} `agentos {' '.join(path)}`\n")
        if helps.get(tuple(path)):
            out.append(helps[tuple(path)] + "\n")
        opts = _options(parser)
        if opts and not subs:
            out += ["| Argument | Meaning |", "| --- | --- |", *opts, ""]
    for action in subs:
        for choice in action._choices_actions:
            helps[(*path, choice.dest)] = choice.help or ""
        for name, sub in action.choices.items():
            _walk(sub, [*path, name], helps, out)


def render() -> str:
    from agentos.cli import build_parser

    out = ["# Command reference", "",
           "Generated by `agentos gen docs` from the command parser; do not edit by hand. Every command also",
           "accepts `--json` for machine-readable output and `--actor` to name who is acting.", ""]
    _walk(build_parser(), [], {}, out)
    return "\n".join(out).rstrip() + "\n"


def generate(path: Path) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return str(path)
